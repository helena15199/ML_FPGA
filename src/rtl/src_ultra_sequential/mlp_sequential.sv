// -----------------------------------------------------------------------------
// mlp_sequential.sv - V2
// Top-level sequential MLP engine using one shared ACT_W for network input,
// activation RAMs, LUT words and final network output.
// -----------------------------------------------------------------------------

`include "scales.vh"

module mlp_sequential #(
    parameter int ACT_W           = `ACT_W,
    parameter int WEIGHT_W        = `WEIGHT_W,
    parameter int BIAS_W          = `BIAS_W,
    parameter int DSP_PW          = `DSP_PW,
    parameter int INPUT_SIZE      = `N0,
    parameter int OUTPUT_SIZE     = {output_size_expr},
    parameter int NUM_LINEAR_CFG  = `NUM_LINEAR,
    parameter int MAX_NEURONS     = 66,
    parameter int VEC_AW          = (MAX_NEURONS > 1) ? $clog2(MAX_NEURONS) : 1
)(
    input  logic                      clk,
    input  logic                      rstn,

    input  logic                      input_frame_full,
    input  logic                      output_busy,
    output logic                      input_consume_pulse,
    output logic                      output_produce_pulse,

    output logic                      vec_rd_en,
    output logic                      vec_rd_bank_sel,
    output logic [VEC_AW-1:0]         vec_rd_addr,
    input  logic signed [ACT_W-1:0]   vec_rd_data,

    output logic                      vec_wr_en,
    output logic                      vec_wr_bank_sel,
    output logic [VEC_AW-1:0]         vec_wr_addr,
    output logic signed [ACT_W-1:0]   vec_wr_data,

    output logic                      busy,
    output logic                      done_pulse
);

    // Model-dependent ROM sizes generated by Python.
    localparam int WEIGHT_DEPTH =
    {weight_depth_expr};

    localparam int BIAS_DEPTH =
    {bias_depth_expr};

    // Activation LUT depths generated from the model configuration.
    {act_depth_localparams}

    localparam int ACT_DEPTH_RAW = {act_depth_sum_expr};
    localparam int ACT_DEPTH = (ACT_DEPTH_RAW > 0) ? ACT_DEPTH_RAW : 1;

    localparam int WEIGHT_ADDR_W = (WEIGHT_DEPTH > 1) ? $clog2(WEIGHT_DEPTH) : 1;
    localparam int BIAS_ADDR_W   = (BIAS_DEPTH   > 1) ? $clog2(BIAS_DEPTH)   : 1;
    localparam int ACT_ADDR_W    = (ACT_DEPTH    > 1) ? $clog2(ACT_DEPTH)    : 1;
    localparam int LAYER_AW      = (NUM_LINEAR_CFG > 1) ? $clog2(NUM_LINEAR_CFG) : 1;
    localparam int DSP_AW        = ACT_W + 1;
    localparam int DSP_BW        = ((WEIGHT_W > ACT_W) ? WEIGHT_W : ACT_W);

    logic [LAYER_AW-1:0]              layer_idx;
    logic                             load_layer_cfg;
    logic                             use_lut_act;

    logic                             weight_en;
    logic [WEIGHT_ADDR_W-1:0]         weight_addr;
    logic signed [WEIGHT_W-1:0]       weight_data;

    logic                             bias_en;
    logic [BIAS_ADDR_W-1:0]           bias_addr;
    logic signed [BIAS_W-1:0]         bias_data;

    logic                             act_rom_en;
    logic signed [ACT_W-1:0]          act_x;
    logic [ACT_ADDR_W-1:0]            act_base_addr;
    logic [$clog2(ACT_W+1)-1:0]       act_lut_n;
    logic signed [ACT_W-1:0]          act_ya;
    logic signed [ACT_W-1:0]          act_yb;
    logic [ACT_W-1:0]                 act_frac;

    logic                             dsp_ce;
    logic                             dsp_first_mac;
    logic [1:0]                       dsp_mode;
    logic signed [DSP_AW-1:0]         dsp_A;
    logic signed [DSP_BW-1:0]         dsp_B;
    logic signed [DSP_PW-1:0]         dsp_C;
    logic signed [DSP_PW-1:0]         dsp_P;

    logic signed [ACT_W-1:0]          datapath_out_data;
    assign vec_wr_data = datapath_out_data;

    mlp_sequential_ctrl #(
        .INPUT_SIZE     (INPUT_SIZE),
        .OUTPUT_SIZE    (OUTPUT_SIZE),
        .NUM_LINEAR_CFG (NUM_LINEAR_CFG),
        .VEC_AW         (VEC_AW),
        .WEIGHT_ADDR_W  (WEIGHT_ADDR_W),
        .BIAS_ADDR_W    (BIAS_ADDR_W),
        .LAYER_AW       (LAYER_AW)
    ) u_ctrl (
        .clk                 (clk),
        .rstn                (rstn),
        .input_frame_full    (input_frame_full),
        .output_busy         (output_busy),
        .input_consume_pulse (input_consume_pulse),
        .output_produce_pulse(output_produce_pulse),
        .layer_idx           (layer_idx),
        .load_layer_cfg      (load_layer_cfg),
        .use_lut_act         (use_lut_act),
        .vec_rd_en           (vec_rd_en),
        .vec_rd_bank_sel     (vec_rd_bank_sel),
        .vec_rd_addr         (vec_rd_addr),
        .vec_wr_en           (vec_wr_en),
        .vec_wr_bank_sel     (vec_wr_bank_sel),
        .vec_wr_addr         (vec_wr_addr),
        .weight_en           (weight_en),
        .weight_addr         (weight_addr),
        .bias_en             (bias_en),
        .bias_addr           (bias_addr),
        .act_rom_en          (act_rom_en),
        .dsp_ce              (dsp_ce),
        .dsp_first_mac       (dsp_first_mac),
        .dsp_mode            (dsp_mode),
        .busy                (busy),
        .compute_done_pulse  (done_pulse)
    );

    mlp_sequential_datapath #(
        .NUM_LINEAR_CFG(NUM_LINEAR_CFG),
        .ACT_W         (ACT_W),
        .WEIGHT_W      (WEIGHT_W),
        .BIAS_W        (BIAS_W),
        .DSP_PW        (DSP_PW),
        .LEAK_SHIFT    (`LEAK_SHIFT),
        .ACT_ADDR_W    (ACT_ADDR_W),
        .LAYER_AW      (LAYER_AW),
        .DSP_AW        (DSP_AW),
        .DSP_BW        (DSP_BW)
    ) u_datapath (
        .clk             (clk),
        .rstn            (rstn),
        .layer_idx       (layer_idx),
        .load_layer_cfg  (load_layer_cfg),
        .vec_rd_data     (vec_rd_data),
        .weight_data     (weight_data),
        .bias_data       (bias_data),
        .dsp_P           (dsp_P),
        .dsp_mode        (dsp_mode),
        .act_ya          (act_ya),
        .act_yb          (act_yb),
        .act_frac        (act_frac),
        .use_lut_act     (use_lut_act),
        .act_x           (act_x),
        .act_base_addr   (act_base_addr),
        .act_lut_n       (act_lut_n),
        .dsp_A           (dsp_A),
        .dsp_B           (dsp_B),
        .dsp_C           (dsp_C),
        .out_data        (datapath_out_data)
    );

    rom_weight_all #(
        .WEIGHT_W   (WEIGHT_W),
        .DEPTH      (WEIGHT_DEPTH),
        .ADDR_WIDTH (WEIGHT_ADDR_W)
    ) u_rom_weight_all (
        .clk  (clk),
        .en   (weight_en),
        .addr (weight_addr),
        .data (weight_data)
    );

    rom_bias_all #(
        .BIAS_W     (BIAS_W),
        .DEPTH      (BIAS_DEPTH),
        .ADDR_WIDTH (BIAS_ADDR_W)
    ) u_rom_bias_all (
        .clk  (clk),
        .en   (bias_en),
        .addr (bias_addr),
        .data (bias_data)
    );

    rom_act_all #(
        .ACT_W      (ACT_W),
        .DEPTH      (ACT_DEPTH),
        .ADDR_WIDTH (ACT_ADDR_W)
    ) u_rom_act_all (
        .clk       (clk),
        .en        (act_rom_en),
        .base_addr (act_base_addr),
        .lut_n     (act_lut_n),
        .x         (act_x),
        .ya        (act_ya),
        .yb        (act_yb),
        .frac      (act_frac)
    );

    dsp #(
        .A_WIDTH(DSP_AW),
        .B_WIDTH(DSP_BW),
        .P_WIDTH(DSP_PW)
    ) u_dsp (
        .clk       (clk),
        .rstn      (rstn),
        .ce        (dsp_ce),
        .first_mac (dsp_first_mac),
        .A         (dsp_A),
        .B         (dsp_B),
        .C         (dsp_C),
        .P         (dsp_P)
    );

endmodule

