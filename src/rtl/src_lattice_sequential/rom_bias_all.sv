// -----------------------------------------------------------------------------
// rom_bias_all.sv
// Synchronous ROM containing all MLP bias values.
// Memory contents are generated inline by Python to avoid external files.
// -----------------------------------------------------------------------------

module rom_bias_all #(
    parameter int BIAS_W     = 16,
    parameter int DEPTH      = 1,
    parameter int ADDR_WIDTH = (DEPTH > 1) ? $clog2(DEPTH) : 1
)(
    input  logic                         clk,
    input  logic                         en,
    input  logic [ADDR_WIDTH-1:0]        addr,
    output logic signed [BIAS_W-1:0]     data
);

    // Small ROM: kept in logic/distributed RAM to save EBRs.
    logic signed [BIAS_W-1:0] mem [0:DEPTH-1];

    // Synthesizable initialization generated by Python.
    initial begin
        {memory_bias}
    end

    always_ff @(posedge clk) begin
        if (en) begin
            data <= mem[addr];
        end
    end

endmodule
