// -----------------------------------------------------------------------------
// rom_weight_all.sv
// Synchronous ROM containing all MLP weights.
// Memory contents are hard-coded to avoid external file-loading issues.
// -----------------------------------------------------------------------------

module rom_weight_all #(
    parameter int WEIGHT_W   = 16,
    parameter int DEPTH      = 1,
    parameter int ADDR_WIDTH = (DEPTH > 1) ? $clog2(DEPTH) : 1
)(
    input  logic                         clk,
    input  logic                         en,
    input  logic [ADDR_WIDTH-1:0]        addr,
    output logic signed [WEIGHT_W-1:0]     data
);

    (* syn_romstyle = "block_rom", syn_ramstyle = "block_ram" *)
    logic signed [WEIGHT_W-1:0] mem [0:DEPTH-1];

    // Synthesizable initialization generated by Python.
    initial begin
        {memory_weight}
    end

    always_ff @(posedge clk) begin
        if (en) begin
            data <= mem[addr];
        end
    end

endmodule
