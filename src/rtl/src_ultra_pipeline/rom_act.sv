// -----------------------------------------------------------------------------
// rom_act.sv
// Synchronous ROM containing the activation LUT values of a single MLP layer.
// Memory contents are generated directly by Python.
// -----------------------------------------------------------------------------

module {module_act_name} #(
    parameter int ACT_W      = 16,
    parameter int DEPTH      = 1,
    parameter int ADDR_WIDTH = (DEPTH > 1) ? $clog2(DEPTH) : 1
)(
    input  logic                         clk,
    input  logic                         en,

    input  logic [$clog2(ACT_W+1)-1:0]   lut_n,
    input  logic signed [ACT_W-1:0]      x,

    output logic signed [ACT_W-1:0]      ya,
    output logic signed [ACT_W-1:0]      yb,
    output logic [ACT_W-1:0]             frac
);

    localparam int LUTN_W = $clog2(ACT_W+1);
    localparam logic [LUTN_W-1:0] ACT_W_L = LUTN_W'(ACT_W);

    // Small activation ROM: kept in logic/distributed RAM to save EBRs.
    logic signed [ACT_W-1:0] mem [0:DEPTH-1];

    logic [ACT_W-1:0] x_u;
    logic [ACT_W-1:0] addr_mask;
    logic [ACT_W-1:0] frac_mask;
    logic [ACT_W-1:0] local_addr_a_w;
    logic [ACT_W-1:0] local_addr_b_w;
    logic [ACT_W-1:0] frac_w;

    logic [ADDR_WIDTH-1:0] rd_addr_a;
    logic [ADDR_WIDTH-1:0] rd_addr_b;

    int unsigned shift_addr;

    // Synthesizable initialization generated by Python.
    initial begin
        {memory_act_function}
    end

    always_comb begin
        x_u            = x;
        local_addr_a_w = '0;
        local_addr_b_w = '0;
        frac_w         = '0;
        addr_mask      = '0;
        frac_mask      = '0;
        shift_addr     = 0;

        if (lut_n != '0) begin
            shift_addr = ACT_W - lut_n;

            local_addr_a_w = x_u >> shift_addr;

            if (lut_n >= ACT_W_L) begin
                addr_mask = {ACT_W{1'b1}};
            end else begin
                addr_mask = ({{(ACT_W-1){1'b0}}, 1'b1} << lut_n)
                          - {{(ACT_W-1){1'b0}}, 1'b1};
            end

            local_addr_b_w = (local_addr_a_w + {{(ACT_W-1){1'b0}}, 1'b1}) & addr_mask;

            if (shift_addr == 0) begin
                frac_w = '0;
            end else if (shift_addr >= ACT_W) begin
                frac_w = x_u;
            end else begin
                frac_mask = ({{(ACT_W-1){1'b0}}, 1'b1} << shift_addr)
                          - {{(ACT_W-1){1'b0}}, 1'b1};
                frac_w    = x_u & frac_mask;
            end
        end

        rd_addr_a = ADDR_WIDTH'(local_addr_a_w);
        rd_addr_b = ADDR_WIDTH'(local_addr_b_w);
    end

    always_ff @(posedge clk) begin
        if (en) begin
            ya   <= mem[rd_addr_a];
            yb   <= mem[rd_addr_b];
            frac <= frac_w;
        end
    end

endmodule
